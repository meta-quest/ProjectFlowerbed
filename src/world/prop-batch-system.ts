/**
 * Prop instancing and LOD (legacy MeshInstancingSystem, LODInstancedMesh and
 * LODWithHysteresis).
 *
 * Repeated island props (fences, planters, benches, bridges) are redrawn as
 * one InstancedMesh per prop type and detail level; every 0.2 s each
 * placement moves to the level chosen by its distance from the viewer, using
 * the legacy distances (6 / 30 m). The three hero props (gazebo, pergola,
 * hero tree) become THREE.LOD objects at 15 / 40 m with 5 m hysteresis.
 * Authored scene nodes keep their transforms; only their visuals are hidden.
 */

import {
  AssetManager,
  InstancedMesh,
  LOD,
  Matrix4,
  Mesh,
  Object3D,
  Vector3,
  createSystem,
  type Material,
} from '@iwsdk/core';
import { islandReady } from './island-state.js';

interface LodSpec {
  /** Scene node name prefix (generated by scripts/generate-flowerbed-scene.mjs). */
  prefix: RegExp;
  /** Manifest ids of the detail levels after the base model. */
  levels: string[];
  distances: number[];
  instanced: boolean;
}

const SPECS: LodSpec[] = [
  { prefix: /^Fence 01 01 /, levels: ['lod-fence-a-0', 'lod-fence-a-1'], distances: [6, 30], instanced: true },
  { prefix: /^Fence 01 03 /, levels: [], distances: [], instanced: true },
  { prefix: /^Fence 01 04 /, levels: [], distances: [], instanced: true },
  { prefix: /^Bench /, levels: ['lod-bench-0', 'lod-bench-1'], distances: [6, 30], instanced: true },
  { prefix: /^Bridge /, levels: [], distances: [], instanced: true },
  {
    prefix: /^Planter Circular 01 /,
    levels: ['lod-planter-round-a-0', 'lod-planter-round-a-1'],
    distances: [6, 30],
    instanced: true,
  },
  {
    prefix: /^Planter Circular 02 /,
    levels: ['lod-planter-round-b-0', 'lod-planter-round-b-1'],
    distances: [6, 30],
    instanced: true,
  },
  {
    prefix: /^Planter Long02 /,
    levels: ['lod-planter-long-b-0', 'lod-planter-long-b-1'],
    distances: [6, 30],
    instanced: true,
  },
  {
    prefix: /^Planter Long04 /,
    levels: ['lod-planter-long-d-0', 'lod-planter-long-d-1'],
    distances: [6, 30],
    instanced: true,
  },
  { prefix: /^Gazebo /, levels: ['lod-gazebo-0', 'lod-gazebo-1'], distances: [15, 40], instanced: false },
  { prefix: /^Pergola /, levels: ['lod-pergola-0', 'lod-pergola-1'], distances: [15, 40], instanced: false },
  { prefix: /^Tree Hero /, levels: ['lod-tree-hero-0', 'lod-tree-hero-1'], distances: [15, 40], instanced: false },
];

const HYSTERESIS = 5;
const REFRESH = 0.2;

interface LevelBatch {
  /** One InstancedMesh per primitive of the level's model. */
  meshes: InstancedMesh[];
  /** Model-local matrices of those primitives. */
  locals: Matrix4[];
}

interface Batch {
  spec: LodSpec;
  placements: Matrix4[];
  positions: Vector3[];
  levels: LevelBatch[];
}

/** Visual meshes of a model with their matrices relative to the model root. */
function visualMeshes(root: Object3D): { mesh: Mesh; local: Matrix4 }[] {
  root.updateMatrixWorld(true);
  const inverse = new Matrix4().copy(root.matrixWorld).invert();
  const out: { mesh: Mesh; local: Matrix4 }[] = [];
  root.traverse((node) => {
    const mesh = node as Mesh;
    if (!mesh.isMesh || node.userData?.collider || !node.visible) return;
    out.push({ mesh, local: new Matrix4().multiplyMatrices(inverse, mesh.matrixWorld) });
  });
  return out;
}

export class PropBatchSystem extends createSystem({}) {
  private batches: Batch[] = [];
  private ready = false;
  private loading = false;
  private timer = 0;
  private viewer = new Vector3();
  private tmp = new Matrix4();

  override update(delta: number): void {
    if (!this.ready) {
      if (!this.loading && islandReady.peek()) void this.build();
      return;
    }
    this.timer += delta;
    if (this.timer < REFRESH) return;
    this.timer = 0;
    this.world.camera.getWorldPosition(this.viewer);
    for (const batch of this.batches) this.assign(batch);
  }

  private async build(): Promise<void> {
    this.loading = true;
    const ids = [...new Set(SPECS.flatMap((spec) => spec.levels))];
    await Promise.all(ids.map((id) => AssetManager.loadGLTFById(id).catch(() => null)));
    const props = this.world.getSceneObject('island-props');
    if (!props) return;
    for (const spec of SPECS) {
      const roots = props.children.filter((child) => spec.prefix.test(child.name));
      if (roots.length === 0) continue;
      if (spec.instanced) this.instance(spec, roots);
      else roots.forEach((root) => this.lod(spec, root));
    }
    this.ready = true;
  }

  private instance(spec: LodSpec, roots: Object3D[]): void {
    const base = visualMeshes(roots[0]);
    if (base.length === 0) return;
    const levelModels: { mesh: Mesh; local: Matrix4 }[][] = [base];
    for (const id of spec.levels) {
      const gltf = AssetManager.getGLTF(id);
      if (gltf) levelModels.push(visualMeshes(gltf.scene));
    }
    const batch: Batch = { spec, placements: [], positions: [], levels: [] };
    for (const root of roots) {
      root.updateMatrixWorld(true);
      batch.placements.push(root.matrixWorld.clone());
      batch.positions.push(new Vector3().setFromMatrixPosition(root.matrixWorld));
      // Hide authored visuals; colliders were already extracted.
      for (const { mesh } of visualMeshes(root)) mesh.visible = false;
    }
    for (const model of levelModels) {
      const level: LevelBatch = { meshes: [], locals: [] };
      model.forEach(({ mesh, local }, i) => {
        // Detail levels reuse the base (overridden) materials; only geometry changes.
        const material = base[Math.min(i, base.length - 1)].mesh.material as Material;
        const instanced = new InstancedMesh(mesh.geometry, material, roots.length);
        instanced.name = `props:${spec.prefix.source}`;
        instanced.count = 0;
        // Keep the authored shadow choice (legacy casters: trees, benches, bridges).
        instanced.castShadow = base[0].mesh.castShadow;
        instanced.receiveShadow = true;
        instanced.frustumCulled = false;
        this.scene.add(instanced);
        level.meshes.push(instanced);
        level.locals.push(local);
      });
      batch.levels.push(level);
    }
    this.batches.push(batch);
    this.world.camera.getWorldPosition(this.viewer);
    this.assign(batch);
  }

  private assign(batch: Batch): void {
    const counts = batch.levels.map(() => 0);
    const distances = batch.spec.distances;
    for (let i = 0; i < batch.placements.length; i++) {
      const d = batch.positions[i].distanceTo(this.viewer);
      let level = 0;
      for (let k = 0; k < distances.length && k + 1 < batch.levels.length; k++) {
        if (d >= distances[k]) level = k + 1;
      }
      const target = batch.levels[level];
      const slot = counts[level]++;
      target.meshes.forEach((mesh, m) => {
        this.tmp.multiplyMatrices(batch.placements[i], target.locals[m]);
        mesh.setMatrixAt(slot, this.tmp);
      });
    }
    batch.levels.forEach((level, k) => {
      for (const mesh of level.meshes) {
        mesh.count = counts[k];
        mesh.instanceMatrix.needsUpdate = true;
      }
    });
  }

  private lod(spec: LodSpec, root: Object3D): void {
    const base = visualMeshes(root);
    if (base.length === 0) return;
    const lod = new LOD();
    lod.name = `lod:${root.name}`;
    root.updateMatrixWorld(true);
    root.matrixWorld.decompose(lod.position, lod.quaternion, lod.scale);
    const level0 = new Object3D();
    for (const { mesh, local } of base) {
      const copy = new Mesh(mesh.geometry, mesh.material);
      local.decompose(copy.position, copy.quaternion, copy.scale);
      copy.castShadow = mesh.castShadow;
      copy.receiveShadow = mesh.receiveShadow;
      level0.add(copy);
      mesh.visible = false;
    }
    lod.addLevel(level0, 0);
    spec.levels.forEach((id, k) => {
      const gltf = AssetManager.getGLTF(id);
      if (!gltf) return;
      const level = new Object3D();
      visualMeshes(gltf.scene).forEach(({ mesh, local }, i) => {
        // Reuse the base (overridden) materials for consistent shading.
        const copy = new Mesh(mesh.geometry, base[Math.min(i, base.length - 1)].mesh.material);
        local.decompose(copy.position, copy.quaternion, copy.scale);
        copy.castShadow = true;
        copy.receiveShadow = true;
        level.add(copy);
      });
      lod.addLevel(level, spec.distances[k], HYSTERESIS / spec.distances[k]);
    });
    this.scene.add(lod);
  }
}
